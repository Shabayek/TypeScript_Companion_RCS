/**
 * `npm run i18n:build -- <language>`: turns translated worklists
 * (translations/<language>/*.txt) into overlay files under
 * src/content/locales/<language>/, which the app loads and
 * `npm run validate:content` checks.
 *
 * A line still identical to the English one is left out, so the app falls
 * back to English there. Fenced code comes from the English text (the ⟦F1⟧
 * tokens), never from the translation. French typography (no-break spaces
 * before : ; ! ? and inside « ») is applied outside code.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { allUnits, numbered, readWorklist } from './worklists';
import { decode, encode, setPath } from './units';

const NBSP = '\u00a0';
const NNBSP = '\u202f';

/** Per-language typography, applied to prose only (never inside `code` or fences). */
function typography(language: string, text: string): string {
  if (language !== 'fr') return text;
  return text
    .split(/(```[\s\S]*?```|`[^`\n]*`)/)
    .map((part, index) =>
      index % 2 === 1
        ? part
        : part
            .replace(/ ([:])/g, `${NBSP}$1`)
            .replace(/ ([;!?])/g, `${NNBSP}$1`)
            .replace(/« /g, `«${NBSP}`)
            .replace(/ »/g, `${NBSP}»`),
    )
    .join('');
}

const HEADERS: Record<string, { type: string; name: string }> = {
  course: { type: 'CourseOverlay', name: 'COURSE' },
  glossary: { type: 'GlossaryOverlay', name: 'GLOSSARY' },
  cheatsheet: { type: 'CheatsheetOverlay', name: 'CHEATSHEET' },
  decoder: { type: 'DecoderOverlay', name: 'DECODER' },
};

function getPath(target: unknown, path: readonly (string | number)[]): unknown {
  let node = target;
  for (const key of path) {
    if (node === null || typeof node !== 'object') return undefined;
    node = (node as Record<string | number, unknown>)[key];
  }
  return node;
}

/** Inline code must come through unchanged; a missing or new span is worth a look. */
function spanWarnings(where: string, english: string, translated: string): string[] {
  const spans = (text: string) => (text.match(/``.+?``|`[^`]+`/g) ?? []).sort().join(' ');
  const problems: string[] = [];
  if (spans(english) !== spans(translated)) problems.push(`${where}: inline code differs from the English`);
  const tokens = (text: string) => (text.match(/⟦F\d+⟧/g) ?? []).join(' ');
  if (tokens(english) !== tokens(translated)) problems.push(`${where}: code block tokens differ from the English`);
  return problems;
}

export const warnings: string[] = [];

export function buildLanguage(language: string): { file: string; units: number; translated: number }[] {
  const report: { file: string; units: number; translated: number }[] = [];
  const outDir = join('src', 'content', 'locales', language);
  mkdirSync(outDir, { recursive: true });
  for (const [name, units] of allUnits()) {
    const english = numbered(units);
    const translated = readWorklist(join('translations', language, `${name}.txt`));
    const snapshot = readWorklist(join('translations', 'en', `${name}.txt`));
    if (translated.size > 0 && english.some((item, index) => snapshot.get(index + 1) !== item.line)) {
      throw new Error(`The English of ${name} changed since the worklists were made: run \`npm run i18n:extract -- ${language}\` first.`);
    }
    const number = new Map(english.map((item, index) => [item.text, index + 1]));
    const overlay: Record<string, unknown> = {};
    let count = 0;
    for (const unit of units) {
      const id = number.get(unit.text) ?? 0;
      const line = translated.get(id);
      const source = encode(unit.text);
      if (line === undefined || line === source.line) continue;
      warnings.push(...spanWarnings(`${name} @${id}`, source.line, line));
      setPath(overlay, unit.path, typography(language, decode(line, source.fences)));
      count += 1;
    }
    // An array (recap points, check names…) is taken whole: an item left in
    // English must still be there, not a hole.
    for (const unit of units) {
      const last = unit.path.reduce<number>((found, key, index) => (typeof key === 'number' ? index : found), -1);
      if (last < 0 || !Array.isArray(getPath(overlay, unit.path.slice(0, last)))) continue;
      if (getPath(overlay, unit.path) === undefined) setPath(overlay, unit.path, unit.text);
    }
    report.push({ file: name, units: units.length, translated: count });
    if (count === 0) continue;
    const header = HEADERS[name] ?? { type: 'ModuleOverlay', name: 'LESSONS' };
    const body = JSON.stringify(overlay, null, 2);
    writeFileSync(
      join(outDir, `${name}.ts`),
      [
        `// Generated by \`npm run i18n:build -- ${language}\` from translations/${language}/${name}.txt. Edit the worklist, not this file.`,
        `import type { ${header.type} } from '../../overlay';`,
        '',
        `export const ${header.name}: ${header.type} = ${body};`,
        '',
      ].join('\n'),
    );
  }
  return report;
}

{
  const language = process.argv.slice(2).find((arg) => arg !== '--');
  if (!language) throw new Error('Usage: npm run i18n:build -- <language>');
  for (const item of buildLanguage(language)) {
    if (item.translated > 0) console.log(`${item.file}: ${item.translated} of ${item.units} units`);
  }
  for (const warning of warnings) console.warn(`warning: ${warning}`);
}
