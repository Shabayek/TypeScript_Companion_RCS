/**
 * The lesson catalog (src/content/generated/catalog.ts): what the app knows
 * about each lesson without loading its steps (titles, minutes, step ids and
 * kinds). Written by `npm run content:catalog` (scripts/generateCatalog.ts);
 * `tests/contentLoading.test.ts` fails when the committed file is stale.
 */
import { fileURLToPath } from 'node:url';
import { LESSONS } from '../src/content/lessons';
import type { Lesson, LessonMeta } from '../src/content/schema';

export const CATALOG_PATH = fileURLToPath(new URL('../src/content/generated/catalog.ts', import.meta.url));

export function lessonMeta(lesson: Lesson): LessonMeta {
  return {
    id: lesson.id,
    moduleId: lesson.moduleId,
    order: lesson.order,
    title: { story: lesson.title.story, explorer: lesson.title.explorer, pro: lesson.title.pro },
    estMinutes: lesson.estMinutes,
    difficulty: lesson.difficulty ?? 1,
    prereqs: [...(lesson.prereqs ?? [])],
    concepts: [...lesson.concepts],
    steps: lesson.steps.map((step) => ({
      id: step.id,
      kind: step.kind,
      ...(step.bonus ? { bonus: true as const } : {}),
      ...(step.runtime === 'modern' ? { modern: true as const } : {}),
    })),
  };
}

/** The file's exact text, so the test can compare it byte for byte. */
export function renderCatalog(lessons: readonly Lesson[] = LESSONS): string {
  const entries = lessons.map((lesson) => `  ${JSON.stringify(lessonMeta(lesson))},`).join('\n');
  return [
    '// Generated by `npm run content:catalog` from src/content/lessons. Do not edit by hand.',
    "import type { LessonMeta } from '../schema';",
    '',
    'export const LESSON_CATALOG: readonly LessonMeta[] = [',
    entries,
    '];',
    '',
  ].join('\n');
}
